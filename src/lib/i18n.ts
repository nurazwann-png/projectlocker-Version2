const DICTS = { en, ms } as const;

export type Translate = (key: TKey, vars?: Record<string, string | number>) => string;

export function useT(): Translate {
  const { appearance } = useAppearance();
  const lang = appearance.lang;
  return useCallback<Translate>((key, vars) => {
    let s = (lang === "ms" ? DICTS.ms[key] : undefined) ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  }, [lang]);
}
